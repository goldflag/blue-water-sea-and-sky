    #[test]
    fn a_foundering_hull_boils_and_the_sea_goes_quiet() {
        let mut sinkings = Sinkings::default();
        let hull = |y: f64| DrawnHull {
            id: "fletcher",
            position: [100.0, y, 200.0],
            heading: 0.3,
            pitch: 0.0,
            length: 114.0,
            beam: 12.0,
            lost: false,
        };
        let mut out = Vec::new();
        // Riding a heavy sea's heave (±2 m) she is afloat: nothing.
        for frame in 0..60 * 30 {
            let heave = 2.0 * (f64::from(frame) / 30.0 * 0.7).sin();
            sinkings.update(1.0 / 30.0, [hull(heave)], 4.5, &mut out);
        }
        assert!(out.is_empty() && sinkings.is_empty());
        // Settling to 6 m down over a minute, she boils and the sea lifts over her.
        let mut settling = Vec::new();
        for frame in 0..60 * 30 {
            out.clear();
            let y = -6.0 * f64::from(frame) / (60.0 * 30.0);
            sinkings.update(1.0 / 30.0, [hull(y)], 4.5, &mut out);
            settling.extend(out.iter().copied());
        }
        let boils = settling.iter().filter(|i| i.displacement > 0.0).count();
        let lifts = settling.iter().filter(|i| i.head < 0.0).count();
        assert!(boils > 5 && lifts > 20, "{boils} boils, {lifts} lifts");
        for i in &settling {
            assert!((i.from[0] - 100.0).hypot(i.from[1] - 200.0) < 60.0);
        }
        // Down by the head, her stern still up, she has not gone under; drawn going deeper she goes under once (one
        // bulge), then boils die away while her wreck is still drawn.
        let mut bulges = 0;
        let (mut early, mut late) = (0, 0);
        for frame in 0..((QUIET_AFTER + 20.0) * 30.0) as usize {
            out.clear();
            let y = (-6.0 - f64::from(frame as u32) * 0.1).max(-80.0);
            sinkings.update(
                1.0 / 30.0,
                [DrawnHull {
                    pitch: -0.5,
                    ..hull(y)
                }],
                4.5,
                &mut out,
            );
            bulges += out.iter().filter(|i| i.duration == BULGE_SECONDS).count();
            if y > -20.0 {
                assert_eq!(bulges, 0, "under at {y} m with her stern up");
            }
            if frame < 30 * 30 {
                early += out.len();
            } else if frame > 140 * 30 {
                late += out.len();
            }
        }
        assert_eq!(bulges, 1);
        assert!(early > 4 * late.max(1), "{early} early, {late} late");
        assert_eq!(sinkings.len(), 0, "the sea is quiet over her wreck");
        // No longer drawn, she is forgotten once the sea is quiet.
        for _ in 0..(QUIET_AFTER * 30.0) as usize + 30 {
            sinkings.update(1.0 / 30.0, std::iter::empty(), 4.5, &mut out);
        }
        assert!(sinkings.hulls.is_empty());
        // A wreck first seen under (a scene just loaded) stirs nothing.
        out.clear();
        sinkings.update(1.0 / 30.0, [hull(-90.0)], 4.5, &mut out);
        sinkings.update(1.0 / 30.0, [hull(-90.0)], 4.5, &mut out);
        assert!(out.is_empty() && sinkings.is_empty());
        sinkings.reset();
        // A lost hull goes down at once; paused frames add nothing.
        let lost = DrawnHull {
            lost: true,
            ..hull(0.0)
        };
        out.clear();
        sinkings.update(0.0, [lost], 4.5, &mut out);
        assert!(out.is_empty() && sinkings.hulls.is_empty());
        sinkings.update(1.0 / 30.0, [lost], 4.5, &mut out);
        assert!(!sinkings.is_empty() && !out.is_empty());
    }
