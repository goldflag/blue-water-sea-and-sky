//! What strikes the sea, laid into the wake field: a round's crater, a charge going off at or under the surface (a
//! shell's or bomb's burster, a torpedo's warhead against a hull, a depth charge, a magazine beside the water), an
//! aircraft striking the water, and a sinking hull's upwelling and boils. Each becomes a [`WakeImpulse`] that
//! `shaders/wake_field.wgsl` lays on the field over the steps it spans; the field's deep-water dispersion turns it into
//! ring waves, longest first. Visual only: combat never reads these waves. The physics and its numbers:
//! `native/docs/water-effects.md`, "The sea answers what strikes it".

use std::f64::consts::PI;

/// Impulses the step shader takes in one step; more wait for the next.
pub const MAX_IMPULSES: usize = 16;
/// Seawater (kg/m³).
const RHO: f64 = 1025.0;
const GRAVITY: f64 = 9.81;
/// Share of the energy released at or just under the surface that leaves as surface waves. The linear theory's
/// crater (Kranzer and Keller), fitted to measured explosion wave trains, holds the waves' energy as its own potential
/// energy, about 2 % of a near-surface charge's (Le Méhauté and Wang, *Water Waves Generated by Underwater Explosion*,
/// 1996). Taken for impacts too.
pub const WAVE_SHARE: f64 = 0.02;
/// TNT's heat of detonation (J/kg).
pub const TNT: f64 = 4.184e6;
/// A crater's depth over its radius.
const CRATER_ASPECT: f64 = 0.5;
/// The deepest crater (or highest dome) laid (m): a stronger strike widens instead, keeping its energy. Half the field's
/// height bound (`MAX_HEIGHT`), which the underwater view relies on.
pub const DEEPEST: f64 = 4.0;
/// A round's mass from its calibre: half the cube of the calibre in inches, in pounds (13,800 d³ kg).
const ROUND_DENSITY: f64 = 13_800.0;
/// Share of a round's kinetic energy given up as it enters the water: naval-sim's `projectile.rs` keeps 0.75 of its
/// speed.
const ENTRY_LOSS: f64 = 1.0 - 0.75 * 0.75;
/// A carrier aircraft's mass (kg; a Wildcat 3.4 t, a Dauntless 4.9 t loaded).
const AIRCRAFT_MASS: f64 = 4000.0;
/// White water left where a strike tears the surface (the field's foam: 1 dense).
const STRUCK_FOAM: f64 = 1.0;

/// One disturbance of the field: a footprint (a capsule from `from` to `to`, world x, z, of `radius` m; a point when
/// the two are equal) and what it does there over `duration` seconds from `delay` seconds after it is added.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct WakeImpulse {
    pub from: [f64; 2],
    pub to: [f64; 2],
    pub radius: f64,
    /// Height laid at the centre (m), negative a crater, positive a dome, as a Mexican hat (−D (1 − s) e^−s at s =
    /// r²/R², no net volume about a point), raised smoothly over `duration` with no velocity of its own.
    pub displacement: f64,
    /// Pressure head (m of water) held under the footprint as a Gaussian, rising and falling as sin² over `duration`:
    /// positive presses the sea down as a hull does, negative lifts it (an upwelling).
    pub head: f64,
    /// Fresh white water laid over the footprint while it acts (the field's foam, 1 dense).
    pub foam: f64,
    pub delay: f64,
    pub duration: f64,
}

impl WakeImpulse {
    /// A point impulse at world `x`, `z`.
    pub fn at(x: f64, z: f64, radius: f64) -> Self {
        Self {
            from: [x, z],
            to: [x, z],
            radius,
            displacement: 0.0,
            head: 0.0,
            foam: 0.0,
            delay: 0.0,
            duration: 0.0,
        }
    }
}

/// What struck the sea, in the terms its energy is worked out from.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Strike {
    /// A round of `caliber_m` entering the water at `speed` m/s.
    Round { caliber_m: f64, speed: f64 },
    /// `kg` of TNT (or its equivalent) going off `depth` m under the surface (0 at it).
    Charge { kg: f64, depth: f64 },
    /// An aircraft or its wreck striking the water at `speed` m/s.
    Aircraft { speed: f64 },
}

/// Radius and depth (m) of the Mexican hat −D (1 − r²/R²) e^(−r²/R²) holding `energy` J as potential energy, ½ρg∫η²dA =
/// π ρ g D² R² / 8: a crater half as deep as it is wide, at most [`DEEPEST`] deep, no narrower than `least` (a strike too
/// small for the grid is laid wider and shallower, keeping its energy and so its rings' height far off).
pub fn crater_size(energy: f64, least: f64) -> (f64, f64) {
    let product = (8.0 * energy.max(0.0) / (PI * RHO * GRAVITY)).sqrt();
    let mut radius = (product / CRATER_ASPECT).sqrt();
    if CRATER_ASPECT * radius > DEEPEST {
        radius = product / DEEPEST;
    }
    let radius = radius.max(least).max(1e-3);
    (radius, product / radius)
}

/// The largest radius (m) of the gas bubble of a charge of `kg` TNT at `depth` m (Cole, *Underwater Explosions*: 3.4
/// (W / (z + 10))^⅓, the 10 m the atmosphere's head).
pub fn bubble_radius(kg: f64, depth: f64) -> f64 {
    3.4 * (kg.max(0.0) / (depth.max(0.0) + 10.0)).cbrt()
}

/// The wave energy (J) a strike leaves, and whether it lifts the sea (a dome) rather than opening a crater.
pub fn strike_energy(strike: &Strike) -> (f64, bool) {
    match *strike {
        Strike::Round { caliber_m, speed } => {
            let mass = ROUND_DENSITY * caliber_m.max(0.0).powi(3);
            (0.5 * mass * speed * speed * ENTRY_LOSS * WAVE_SHARE, false)
        }
        // A charge whose bubble breaks the surface opens a crater; a deeper one lifts a dome, its waves falling away
        // over the bubble's own radius as the charge goes deeper.
        Strike::Charge { kg, depth } => {
            let bubble = bubble_radius(kg, depth).max(0.1);
            let depth = depth.max(0.0);
            (
                kg.max(0.0) * TNT * WAVE_SHARE * (-depth / bubble).exp(),
                depth > bubble,
            )
        }
        Strike::Aircraft { speed } => (0.5 * AIRCRAFT_MASS * speed * speed * WAVE_SHARE, false),
    }
}

/// A strike at world `x`, `z` as the impulse that lays it: its crater (or dome) sized by its energy, no narrower than
/// `least` m, opening over √(R/g) (a quarter of the period of the waves it sheds, so they leave as from an instant
/// strike while the grid sees a smooth rise), with white water over it. None for a strike with no energy.
pub fn strike_impulse(x: f64, z: f64, strike: &Strike, least: f64) -> Option<WakeImpulse> {
    let (energy, dome) = strike_energy(strike);
    if !(energy > 0.0 && energy.is_finite()) {
        return None;
    }
    let (radius, depth) = crater_size(energy, least);
    Some(WakeImpulse {
        displacement: if dome { depth } else { -depth },
        foam: STRUCK_FOAM,
        duration: (radius / GRAVITY).sqrt(),
        ..WakeImpulse::at(x, z, radius)
    })
}

/// A drawn hull, as the sinking reads her each frame.
#[derive(Clone, Copy, Debug)]
pub struct DrawnHull<'a> {
    pub id: &'a str,
    /// World position of her origin (her waterline at rest: y below 0 is her settling) and her heading (radians
    /// clockwise from −Z).
    pub position: [f64; 3],
    pub heading: f64,
    /// Her trim (radians): a hull going down by the head or the stern keeps her other end up.
    pub pitch: f64,
    pub length: f64,
    pub beam: f64,
    /// Lost (naval-sim's physical loss: foundered, capsized, blown up): she goes down whatever her level.
    pub lost: bool,
}

/// Seconds over which a hull's level is averaged, so the sea's heave does not read as settling.
const LEVEL_SMOOTHING: f64 = 8.0;
/// A hull settled this far below her waterline (m, averaged) is foundering: more than a heavy sea heaves her on
/// average.
const SETTLED: f64 = 1.5;
/// How far further, as a share of her length, she settles before her air pours out at full strength (deck awash).
const AWASH: f64 = 0.03;
/// Her upper works stand this share of her length over her waterline: she has gone under once her highest end and
/// they are under (or when she is no longer drawn).
const UPPER_WORKS: f64 = 0.15;
/// Seconds a hull founders before her air is spent (a wreck settled on a shallow bottom stops boiling).
const AIR_SPENT: f64 = 600.0;
/// Upwelling head over a foundering hull (m of water, lifting) at full strength, for a 250 × 36 m hull.
const UPWELL_HEAD: f64 = 0.3;
/// The bulge where she goes under: head (m, lifting) and how long it acts (s).
const BULGE_HEAD: f64 = 1.0;
const BULGE_SECONDS: f64 = 6.0;
/// The upwelling's pulses: every second, each lasting two, so their sin² envelopes sum to a steady head.
const PULSE_EVERY: f64 = 1.0;
/// Boils a second while she settles (at full strength), and once she has gone (decaying over `BOIL_DECAY`).
const BOILS_SETTLING: f64 = 1.5;
const BOILS_GONE: f64 = 3.0;
const BOIL_DECAY: f64 = 35.0;
/// Seconds after she has gone that the sea goes quiet, and that a hull no longer drawn is forgotten.
const QUIET_AFTER: f64 = 150.0;
/// A boil's air flux (m³/s) for a 250 × 36 m hull: log-uniform between these.
const BOIL_FLUX: [f64; 2] = [0.5, 8.0];

/// A hull's averaged level, and her going down once she founders.
#[derive(Clone, Debug)]
struct Watched {
    id: String,
    seed: u64,
    seen: f64,
    level: f64,
    position: [f64; 3],
    heading: f64,
    length: f64,
    beam: f64,
    lost: bool,
    /// How far into foundering she is, 0 afloat to 1 with her deck awash, and since when she has been.
    settling: f64,
    foundering_since: Option<f64>,
    /// When she went under, once she has.
    gone: Option<f64>,
    next_pulse: f64,
    /// Boils owed (the rate integrated over time) and how many owe the next: an exponential draw, so they come as a
    /// Poisson process whose rate changes as she goes down.
    boil_due: f64,
    boil_wait: f64,
    boils: u64,
}

/// Foundering hulls' upwelling and the air that boils up as they settle and after they have gone, as impulses.
#[derive(Default)]
pub struct Sinkings {
    hulls: Vec<Watched>,
    clock: f64,
}

impl Sinkings {
    /// Hulls going down, or gone and still boiling.
    pub fn len(&self) -> usize {
        self.hulls
            .iter()
            .filter(|h| h.foundering() && h.gone.is_none_or(|gone| self.clock - gone < QUIET_AFTER))
            .count()
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    pub fn reset(&mut self) {
        self.hulls.clear();
    }

    /// A frame of `dt` seconds over the drawn `hulls`: this frame's impulses into `out`, none narrower than `least` m.
    /// A foundering hull that is no longer drawn has gone under. A paused frame (`dt` 0) adds nothing.
    pub fn update<'a>(
        &mut self,
        dt: f64,
        hulls: impl IntoIterator<Item = DrawnHull<'a>>,
        least: f64,
        out: &mut Vec<WakeImpulse>,
    ) {
        if dt.is_nan() || dt <= 0.0 {
            return;
        }
        self.clock += dt;
        let now = self.clock;
        let blend = 1.0 - (-dt / LEVEL_SMOOTHING).exp();
        for hull in hulls {
            let hull = &hull;
            let index = match self.hulls.iter().position(|w| w.id == hull.id) {
                // Afloat again after going under (a new scene's hull of the same name): watched afresh. One still
                // drawn going deeper stays gone.
                Some(i) if self.hulls[i].gone.is_some() && hull.position[1] > -SETTLED => {
                    self.hulls[i] = Watched::new(hull, now);
                    i
                }
                Some(i) => i,
                None => {
                    self.hulls.push(Watched::new(hull, now));
                    self.hulls.len() - 1
                }
            };
            let w = &mut self.hulls[index];
            w.level += (hull.position[1] - w.level) * blend;
            w.position = hull.position;
            w.heading = hull.heading;
            w.lost |= hull.lost;
            w.seen = now;
            let settling = ((-w.level - SETTLED) / (AWASH * w.length)).clamp(0.0, 1.0);
            w.settling = if w.lost {
                1.0
            } else {
                settling.max(w.settling)
            };
            if w.settling > 0.0 && w.foundering_since.is_none() {
                w.foundering_since = Some(now);
            }
            if w.foundering() && w.gone.is_none() && under(hull) {
                w.gone = Some(now);
                out.push(w.bulge(least));
            }
        }
        for w in &mut self.hulls {
            if w.gone.is_none() && w.seen < now {
                if !w.foundering() {
                    continue;
                }
                w.gone = Some(now);
                out.push(w.bulge(least));
            }
            if w.foundering() {
                w.emit(now, dt, least, out);
            }
        }
        // A wreck still drawn stays watched (and quiet); one no longer drawn is forgotten once the sea is quiet.
        self.hulls
            .retain(|w| w.seen == now || now - w.seen < QUIET_AFTER);
    }
}

/// Whether her highest end and her upper works are under the surface.
fn under(hull: &DrawnHull<'_>) -> bool {
    let rise = 0.5 * hull.pitch.sin().abs() + UPPER_WORKS * hull.pitch.cos();
    hull.position[1] + hull.length.max(10.0) * rise < 0.0
}

impl Watched {
    fn new(hull: &DrawnHull<'_>, now: f64) -> Self {
        Self {
            id: hull.id.to_owned(),
            seed: id_hash(hull.id),
            seen: now,
            // Her level averaged from her waterline, so a hull first seen in a trough is not foundering.
            level: 0.0,
            position: hull.position,
            heading: hull.heading,
            length: hull.length.max(10.0),
            beam: hull.beam.max(3.0),
            lost: hull.lost,
            settling: 0.0,
            foundering_since: None,
            // First seen already under (a wreck in a scene just loaded): long gone, and quiet.
            gone: under(hull).then_some(now - QUIET_AFTER),
            next_pulse: now,
            boil_due: 0.0,
            boil_wait: 1.0,
            boils: 0,
        }
    }

    fn foundering(&self) -> bool {
        self.settling > 0.0 || self.gone.is_some()
    }

    /// Her size against a 250 × 36 m battleship's.
    fn size(&self) -> f64 {
        (self.length * self.beam / (250.0 * 36.0)).clamp(0.05, 2.0)
    }

    /// The capsule along her keel, from 0.4 of her length forward of her origin to 0.4 aft.
    fn keel(&self) -> ([f64; 2], [f64; 2]) {
        let (sin, cos) = self.heading.sin_cos();
        let half = 0.4 * self.length;
        let [x, _, z] = self.position;
        (
            [x + sin * half, z - cos * half],
            [x - sin * half, z + cos * half],
        )
    }

    /// The sea heaped over where she went under as the last of her air leaves.
    fn bulge(&self, least: f64) -> WakeImpulse {
        let (from, to) = self.keel();
        WakeImpulse {
            from,
            to,
            radius: (0.6 * self.beam).max(least),
            head: -BULGE_HEAD * self.size().sqrt(),
            foam: STRUCK_FOAM,
            duration: BULGE_SECONDS,
            ..WakeImpulse::at(0.0, 0.0, 0.0)
        }
    }

    fn emit(&mut self, now: f64, dt: f64, least: f64, out: &mut Vec<WakeImpulse>) {
        // Her air spent: long gone, or settled on a bottom too shallow to take her under.
        let spent = match self.gone {
            Some(gone) => now - gone >= QUIET_AFTER,
            None => self
                .foundering_since
                .is_some_and(|since| now - since >= AIR_SPENT),
        };
        if spent {
            return;
        }
        // The upwelling over her while she goes down: overlapping pulses holding a steady lift (from now, not caught up
        // from when she was first seen).
        if self.gone.is_none() {
            if self.next_pulse + PULSE_EVERY < now {
                self.next_pulse = now;
            }
            while self.next_pulse <= now {
                self.next_pulse += PULSE_EVERY;
                let (from, to) = self.keel();
                out.push(WakeImpulse {
                    from,
                    to,
                    radius: (0.5 * self.beam).max(least),
                    head: -UPWELL_HEAD * self.settling * self.size().sqrt(),
                    foam: 0.35 * self.settling,
                    duration: 2.0 * PULSE_EVERY,
                    ..WakeImpulse::at(0.0, 0.0, 0.0)
                });
            }
        }
        let rate = match self.gone {
            None => BOILS_SETTLING * self.settling,
            Some(gone) => BOILS_GONE * (-(now - gone) / BOIL_DECAY).exp(),
        } * self.size().sqrt();
        self.boil_due += rate * dt;
        while self.boil_due >= self.boil_wait {
            self.boil_due -= self.boil_wait;
            self.boils += 1;
            let mut random = Random(self.seed ^ self.boils.wrapping_mul(0x9e37_79b9_7f4a_7c15));
            self.boil_wait = (-(1.0 - random.next()).ln()).max(1e-3);
            out.push(self.boil(&mut random, least));
        }
    }

    /// Air reaching the surface from her: a dome of aerated water as high as a bubble plume's fountain, 1.3 (g Q)^⅔ / g
    /// for a flux Q (the plume's velocity at the surface, 1.6 (g Q)^⅓, squared over 2g), somewhere along her keel.
    fn boil(&self, random: &mut Random, least: f64) -> WakeImpulse {
        let along = (random.next() - 0.5) * 0.9 * self.length;
        let across = (random.next() - 0.5) * 0.6 * self.beam;
        let flux = BOIL_FLUX[0] * (BOIL_FLUX[1] / BOIL_FLUX[0]).powf(random.next()) * self.size();
        let height = (1.3 * (GRAVITY * flux).powf(2.0 / 3.0) / GRAVITY).min(0.5 * DEEPEST);
        let (sin, cos) = self.heading.sin_cos();
        let [x, _, z] = self.position;
        let at = [
            x + sin * along + cos * across,
            z - cos * along + sin * across,
        ];
        let radius = (self.beam * (0.12 + 0.13 * random.next())).max(least);
        WakeImpulse {
            displacement: height,
            foam: 0.9,
            duration: 0.6 + 0.6 * random.next(),
            ..WakeImpulse::at(at[0], at[1], radius)
        }
    }
}

fn id_hash(id: &str) -> u64 {
    id.bytes().fold(0xcbf2_9ce4_8422_2325, |h, b| {
        (h ^ u64::from(b)).wrapping_mul(0x0100_0000_01b3)
    })
}

/// SplitMix64: a hull's boils are the same from run to run.
struct Random(u64);

impl Random {
    fn next(&mut self) -> f64 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        ((z ^ (z >> 31)) >> 11) as f64 / (1u64 << 53) as f64
    }
}

/// The share of a smooth rise (smoothstep) done by `u` of it.
fn risen(u: f64) -> f64 {
    let u = u.clamp(0.0, 1.0);
    u * u * (3.0 - 2.0 * u)
}

/// Ring trains the field remembers, so the hulls' breaking threshold is not taken inside them.
pub const MAX_ZONES: usize = 16;
/// Seconds a strike's ring train is remembered after it starts (its last acts), fading over the last `ZONE_FADE`.
const ZONE_LIFE: f64 = 20.0;
const ZONE_FADE: f64 = 5.0;
/// How far a train's leading waves reach beyond its footprint, at most (m).
const ZONE_REACH: f64 = 200.0;

/// A queued impulse and when it starts on the field's clock.
#[derive(Clone, Copy, Debug)]
struct Queued {
    impulse: WakeImpulse,
    start: f64,
}

/// Where a strike's rings run: its footprint grown at the group speed of its longest waves, √(gR/2) (waves of k =
/// 1/(2R), where the Mexican hat's spectrum has fallen to a sixth of its peak), from when it started until `until`.
#[derive(Clone, Copy, Debug)]
struct Zone {
    from: [f64; 2],
    to: [f64; 2],
    radius: f64,
    speed: f64,
    born: f64,
    until: f64,
}

impl Zone {
    fn reach(&self, now: f64) -> f64 {
        2.0 * self.radius + (self.speed * (now - self.born)).min(ZONE_REACH)
    }

    /// Whether a point lies within `margin` of the zone's reach now.
    fn holds(&self, point: [f64; 2], margin: f64, now: f64) -> bool {
        let along = [self.to[0] - self.from[0], self.to[1] - self.from[1]];
        let offset = [point[0] - self.from[0], point[1] - self.from[1]];
        let length = along[0] * along[0] + along[1] * along[1];
        let t = if length > 1e-9 {
            ((offset[0] * along[0] + offset[1] * along[1]) / length).clamp(0.0, 1.0)
        } else {
            0.0
        };
        let miss = (offset[0] - along[0] * t).hypot(offset[1] - along[1] * t);
        miss + margin <= self.reach(now)
    }
}

/// What strikes the field, waiting or acting, and the ring trains it has started, on the field's own clock.
#[derive(Default)]
pub(crate) struct Disturbances {
    queue: Vec<Queued>,
    zones: Vec<Zone>,
    clock: f64,
}

/// What one step lays: per impulse, (x0, z0, x1, z1) relative to the field's origin and (radius, displacement this
/// step, head this step, foam); per ring train, its path and (reach, the soft margin beyond it, strength 0–1, 0).
pub(crate) struct StepLoad {
    pub impulses: usize,
    pub zones: usize,
}

impl Disturbances {
    pub fn add(&mut self, impulse: WakeImpulse) {
        if self.queue.len() < 512 {
            self.queue.push(Queued {
                start: self.clock + impulse.delay.max(0.0),
                impulse,
            });
        }
    }

    pub fn clear(&mut self) {
        self.queue.clear();
        self.zones.clear();
    }

    /// Whether anything is waiting, acting or still ringing.
    pub fn busy(&self) -> bool {
        !self.queue.is_empty() || !self.zones.is_empty()
    }

    /// One step of `step` seconds about the field's `origin`, then the clock moves on.
    pub fn step(
        &mut self,
        step: f64,
        origin: [f64; 2],
        paths: &mut [[f32; 4]; MAX_IMPULSES],
        shapes: &mut [[f32; 4]; MAX_IMPULSES],
        zone_paths: &mut [[f32; 4]; MAX_ZONES],
        zone_shapes: &mut [[f32; 4]; MAX_ZONES],
    ) -> StepLoad {
        let (t0, t1) = (self.clock, self.clock + step);
        let relative = |p: [f64; 2]| [(p[0] - origin[0]) as f32, (p[1] - origin[1]) as f32];
        let mut count = 0;
        // Those under way first, so a crowded step defers the newest.
        self.queue.sort_by(|a, b| a.start.total_cmp(&b.start));
        for q in &mut self.queue {
            if q.start >= t1 {
                continue;
            }
            if count == MAX_IMPULSES {
                // Too many at once: it waits a step, its course shifted whole (none of it is lost).
                q.start += step;
                continue;
            }
            let i = q.impulse;
            let duration = i.duration.max(step);
            let (u0, u1) = ((t0 - q.start) / duration, (t1 - q.start) / duration);
            let lift = i.displacement * (risen(u1) - risen(u0));
            let middle = (0.5 * (u0 + u1)).clamp(0.0, 1.0);
            let press = i.head * (PI * middle).sin().powi(2);
            let [x0, z0] = relative(i.from);
            let [x1, z1] = relative(i.to);
            paths[count] = [x0, z0, x1, z1];
            shapes[count] = [i.radius as f32, lift as f32, press as f32, i.foam as f32];
            count += 1;
            if u0 <= 0.0 {
                open_zone(&mut self.zones, &i, q.start);
            }
        }
        self.queue
            .retain(|q| q.start + q.impulse.duration.max(step) > t1 + 1e-9);
        self.zones.retain(|z| z.until > t0);
        // The newest trains when there are more than the step takes.
        let skip = self.zones.len().saturating_sub(MAX_ZONES);
        let mut zones = 0;
        for z in &self.zones[skip..] {
            let [x0, z0] = relative(z.from);
            let [x1, z1] = relative(z.to);
            zone_paths[zones] = [x0, z0, x1, z1];
            zone_shapes[zones] = [
                z.reach(t0) as f32,
                (2.0 * z.radius) as f32,
                ((z.until - t0) / ZONE_FADE).clamp(0.0, 1.0) as f32,
                0.0,
            ];
            zones += 1;
        }
        self.clock = t1;
        StepLoad {
            impulses: count,
            zones,
        }
    }
}

/// A train for impulse `i` starting at `start`, or a longer life for one already running that holds it (a sinking hull's
/// pulses and boils keep her train open).
fn open_zone(zones: &mut Vec<Zone>, i: &WakeImpulse, start: f64) {
    let until = start + i.duration + ZONE_LIFE;
    let middle = [0.5 * (i.from[0] + i.to[0]), 0.5 * (i.from[1] + i.to[1])];
    let half = 0.5 * (i.to[0] - i.from[0]).hypot(i.to[1] - i.from[1]);
    if let Some(zone) = zones
        .iter_mut()
        .find(|z| z.holds(middle, half + 2.0 * i.radius, start))
    {
        zone.until = zone.until.max(until);
        return;
    }
    zones.push(Zone {
        from: i.from,
        to: i.to,
        radius: i.radius,
        speed: (GRAVITY * i.radius / 2.0).sqrt(),
        born: start,
        until,
    });
}

#[cfg(test)]
