    struct Uniforms {
        paths: [[f32; 4]; MAX_IMPULSES],
        shapes: [[f32; 4]; MAX_IMPULSES],
        zone_paths: [[f32; 4]; MAX_ZONES],
        zone_shapes: [[f32; 4]; MAX_ZONES],
    }

    impl Uniforms {
        fn new() -> Self {
            Self {
                paths: [[0.0; 4]; MAX_IMPULSES],
                shapes: [[0.0; 4]; MAX_IMPULSES],
                zone_paths: [[0.0; 4]; MAX_ZONES],
                zone_shapes: [[0.0; 4]; MAX_ZONES],
            }
        }

        fn step(&mut self, d: &mut Disturbances, origin: [f64; 2]) -> StepLoad {
            d.step(
                STEP,
                origin,
                &mut self.paths,
                &mut self.shapes,
                &mut self.zone_paths,
                &mut self.zone_shapes,
            )
        }
    }

    #[test]
    fn a_step_lays_each_impulse_whole_over_its_rise() {
        let mut d = Disturbances::default();
        d.add(WakeImpulse {
            displacement: -2.0,
            head: -1.0,
            duration: 0.5,
            ..WakeImpulse::at(10.0, 20.0, 6.0)
        });
        let mut u = Uniforms::new();
        let mut laid = 0.0;
        let mut steps = 0;
        let mut pressed: f32 = 0.0;
        while !d.queue.is_empty() {
            let load = u.step(&mut d, [4.0, 5.0]);
            assert_eq!(load.impulses, 1);
            assert_eq!(u.paths[0], [6.0, 15.0, 6.0, 15.0]);
            laid += f64::from(u.shapes[0][1]);
            pressed = pressed.min(u.shapes[0][2]);
            steps += 1;
        }
        assert_eq!(steps, 15);
        assert!((laid + 2.0).abs() < 1e-5, "{laid}");
        assert!(pressed < -0.95, "{pressed}");
        // Its ring train is remembered after it, growing, then forgotten.
        let first = u.step(&mut d, [4.0, 5.0]);
        assert_eq!(first.zones, 1);
        let reach = u.zone_shapes[0][0];
        for _ in 0..30 {
            u.step(&mut d, [4.0, 5.0]);
        }
        assert!(u.zone_shapes[0][0] > reach);
        for _ in 0..30 * 25 {
            u.step(&mut d, [4.0, 5.0]);
        }
        assert!(!d.busy());
    }

