    fn potential(radius: f64, depth: f64) -> f64 {
        PI * RHO * GRAVITY * depth * depth * radius * radius / 8.0
    }

    #[test]
    fn a_crater_holds_its_energy_however_it_is_bounded() {
        for energy in [1e3, 1e5, 1e6, 3e7, 1e9] {
            for least in [0.0, 4.5, 9.0] {
                let (radius, depth) = crater_size(energy, least);
                assert!(
                    radius >= least && depth <= DEEPEST + 1e-9,
                    "{energy} {least}"
                );
                let held = potential(radius, depth);
                assert!(
                    (held / energy - 1.0).abs() < 1e-9,
                    "{energy} {least}: {held}"
                );
            }
        }
        // Unbounded, half as deep as it is wide.
        let (radius, depth) = crater_size(1e6, 0.0);
        assert!((depth / radius - CRATER_ASPECT).abs() < 1e-9);
    }

    #[test]
